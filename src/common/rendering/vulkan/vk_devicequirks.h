// PF-007 keeps these inherited Vulkan driver workarounds data-only and
// deterministic.  They describe device/driver facts; sampler and ray-query
// quality/configuration policy remains at the call sites.
enum class VkIntelSamplerQuirk
{
	None,
	DisableAnisotropyForNearestFiltering,
	BrokenNearestMipLinear
};

inline const char* VkIntelSamplerQuirkName(VkIntelSamplerQuirk quirk)
{
	switch (quirk)
	{
	case VkIntelSamplerQuirk::DisableAnisotropyForNearestFiltering:
		return "disable-anisotropy-for-nearest-filtering";
	case VkIntelSamplerQuirk::BrokenNearestMipLinear:
		return "broken-nearest-mip-linear";
	default:
		return "none";
	}
}

template<std::size_t N>
inline bool VkDeviceIDInSet(uint32_t deviceID, const uint32_t (&ids)[N])
{
	return std::find(std::begin(ids), std::end(ids), deviceID) != std::end(ids);
}

