inline bool VkHasAmdRayQueryDriverQuirk(uint32_t vendorID, uint32_t driverVersion)
{
	// Inherited AMDVLK guard.  Do not reinterpret vendor-specific driverVersion
	// encoding here: PF-007 deliberately preserves the baseline major<10 test.
	return vendorID == 0x1002 && VK_VERSION_MAJOR(driverVersion) < 10;
}
